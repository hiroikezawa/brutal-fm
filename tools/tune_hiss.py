"""The hiss budget of the factory presets: for each preset (NOISE mode excepted) the smallest TAME step of
tools/gen_bfm_factory.py at which its render (tests/render.c) keeps <= HF_MAX dB above 16 kHz and a spectral
flatness <= FLAT_MAX. Writes tools/factory_tame.txt; run tests/calibrate (CAL=1) afterwards, as the level moves.

  tools/tune_hiss.py            (from the repository root, after ./build.sh)"""
import subprocess
import sys
from pathlib import Path

HF_MAX, FLAT_MAX, STEPS = -20.0, 0.30, 30
ROOT = Path(__file__).resolve().parent.parent
TAME = ROOT / "tools" / "factory_tame.txt"
sys.path.insert(0, str(ROOT / "tools"))


def write(tames):
    lines = ["# generated by tools/tune_hiss.py: name|TAME step (0 = as written)"]
    lines += [f"{n}|{t}" for n, t in tames.items() if t]
    TAME.write_text("\n".join(lines) + "\n")


def measure(idx):
    subprocess.run([sys.executable, "tools/gen_bfm_factory.py", "build/gen/bfm_factory.h"], cwd=ROOT, check=True,
                   capture_output=True)
    subprocess.run(["cc", "-O2", "-w", "-Ibuild/gen", "-o", "build/host/render", "tests/render.c", "-lm"], cwd=ROOT,
                   check=True)
    out = subprocess.run(["build/host/render", "build/tune", str(idx)], cwd=ROOT, check=True, capture_output=True,
                         text=True).stdout.splitlines()[1].split()
    return float(out[-2]), float(out[-1])


def main():
    import gen_bfm_factory as g
    names = [(i, p["name"]) for i, p in enumerate(g.P) if p["mode"] != g.MODES["NOISE"]]
    tames = {}
    write(tames)
    for i, n in names:
        t, first = 0, None
        while True:
            tames[n] = t
            write(tames)
            flat, hf = measure(i)
            first = first or (flat, hf)
            if (hf <= HF_MAX and flat <= FLAT_MAX) or t == STEPS:
                break
            t += 1
        note = ""
        if not (hf <= HF_MAX and flat <= FLAT_MAX):
            note = "  (budget not met"
            if first[1] - hf < 3.0:                  # taming that buys under 3 dB only costs the knobs: none
                t, (flat, hf) = 0, first
                tames[n] = 0
                note += ": left as written"
            note += ")"
        print(f"{n:12s} TAME {t:2d}  flat {flat:.3f}  >16k {hf:6.1f} dB{note}", flush=True)
    write(tames)


if __name__ == "__main__":
    main()
