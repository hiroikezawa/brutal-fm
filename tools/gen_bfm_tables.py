"""Constant tables of the BRUTAL FM engine (integer only: the firmware has no float).

  tools/gen_bfm_tables.py OUT.h

Everything the DSP needs from math.h is computed here once:
  BFM_SINE[1025]      sin(2 pi i / 1024), Q15 (the last entry repeats the first: interpolation)
  BFM_EXP2[257]       2^(i/256), Q30 mantissa, for pitch -> phase increment
  BFM_RATIO_LOG[]     operator frequency ratios as log2(ratio) in Q12 octaves, BFM_RATIO_NAME[] their labels
  BFM_LEVEL[128]      0..127 -> linear gain Q15 (0.375 dB per step: 127 = 0 dB, 1 = -47 dB, 0 = silence)
  BFM_MODAMT[128]     0..127 -> modulation index in Q12 cycles (quadratic: fine control at the bottom)
  BFM_ENV_ATK[128]    attack increment per sample, Q24 (0.3 ms .. 12 s)
  BFM_ENV_DEC[128]    decay / release multiplier per CTL block, Q16 (time to -60 dB 1 ms .. 30 s)
  BFM_FIXED_LOG[128]  fixed operator frequency, log2(f / 8.1758 Hz) Q12 (1 Hz .. 9 kHz)
  BFM_LFO_INC[128]    LFO phase increment per CTL block, Q32 (0.02 Hz .. 40 Hz)
  BFM_HB[]            half-band decimator taps (2x -> 1x), Q15
  BFM_TANH[257]       tanh over -4..4, Q15 (drive / soft clip)
"""
import math
import sys

FS = 44100
CTL = 32
SAT = lambda v, lo, hi: max(lo, min(hi, v))

RATIOS = [  # (ratio, label): harmonic and the inharmonic ones METAL lives on
    (0.25, "0.25"), (0.5, "0.5"), (0.707, "0.71"), (0.75, "0.75"), (1.0, "1"), (1.0595, "1.06"),
    (1.4142, "1.41"), (1.5, "1.5"), (1.732, "1.73"), (2.0, "2"), (2.2361, "2.24"), (2.5, "2.5"),
    (2.7183, "2.72"), (3.0, "3"), (3.1416, "3.14"), (3.5, "3.5"), (4.0, "4"), (4.2, "4.2"),
    (4.5, "4.5"), (5.0, "5"), (5.4, "5.4"), (6.0, "6"), (6.2832, "6.28"), (7.0, "7"), (7.5, "7.5"),
    (8.0, "8"), (9.0, "9"), (9.4248, "9.42"), (10.0, "10"), (11.0, "11"), (11.2, "11.2"), (12.0, "12"),
    (13.0, "13"), (14.0, "14"), (15.0, "15"), (16.0, "16"),
]


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def kaiser_halfband(ntaps, beta):
    """odd-length half-band low-pass (cut-off fs/4), Kaiser window; every other tap is zero"""
    def i0(x):
        s, t, k = 1.0, 1.0, 1
        while t > 1e-12 * s:
            t *= (x / (2 * k)) ** 2
            s += t
            k += 1
        return s
    m = (ntaps - 1) // 2
    h = []
    for n in range(ntaps):
        k = n - m
        sinc = 0.5 if k == 0 else math.sin(math.pi * k / 2) / (math.pi * k)
        w = i0(beta * math.sqrt(1 - (k / m) ** 2)) / i0(beta)
        h.append(sinc * w)
    s = sum(h)
    return [v / s for v in h]


def main():
    L = ["/* generated by tools/gen_bfm_tables.py: do not edit */", "#pragma once",
         f"#define BFM_FS {FS}", f"#define BFM_CTL {CTL}", ""]
    L += arr("BFM_SINE", "int16_t", [SAT(round(32767 * math.sin(2 * math.pi * i / 1024)), -32767, 32767)
                                     for i in range(1025)], 16)
    L += arr("BFM_EXP2", "uint32_t", [round((1 << 30) * 2 ** (i / 256)) for i in range(257)], 8)
    L += [f"#define BFM_NRATIO {len(RATIOS)}"]
    L += arr("BFM_RATIO_LOG", "int16_t", [round(4096 * math.log2(r)) for r, _ in RATIOS], 12)
    L += ["static const char *const BFM_RATIO_NAME[BFM_NRATIO] = {"
          + ", ".join(f'"{n}"' for _, n in RATIOS) + "};"]
    L += arr("BFM_LEVEL", "uint16_t", [0] + [round(32767 * 10 ** (-(127 - i) * 0.375 / 20)) for i in range(1, 128)])
    # modulation amount: index (cycles of phase deviation per unit of the source) 0 .. 4 cycles, quadratic
    L += arr("BFM_MODAMT", "uint16_t", [round(4096 * 4.0 * (i / 127) ** 2) for i in range(128)])
    atk = []
    dec = []
    for i in range(128):
        ms_a = 0.3 * (12000 / 0.3) ** (i / 127)
        atk.append(max(1, round((1 << 24) / (ms_a * FS / 1000))))
        ms_d = 1.0 * (30000 / 1.0) ** (i / 127)              # time to -60 dB
        per_block = 10 ** (-3 * CTL / (ms_d * FS / 1000))
        dec.append(SAT(round(65536 * per_block), 0, 65535))
    L += arr("BFM_ENV_ATK", "uint32_t", atk, 8)
    L += arr("BFM_ENV_DEC", "uint16_t", dec)
    f0 = 440 * 2 ** (-69 / 12)
    L += arr("BFM_FIXED_LOG", "int32_t", [round(4096 * math.log2((1.0 * (9000 / 1.0) ** (i / 127)) / f0))
                                          for i in range(128)], 8)
    L += arr("BFM_LFO_INC", "uint32_t", [round((2 ** 32) * (0.02 * (40 / 0.02) ** (i / 127)) * CTL / FS)
                                          for i in range(128)], 8)
    # what the UI shows for the curves above (tenths of ms, tenths of Hz): no float on the device
    L += arr("BFM_ATK_SHOW", "uint32_t", [round(10 * 0.3 * (12000 / 0.3) ** (i / 127)) for i in range(128)], 8)
    L += arr("BFM_DEC_SHOW", "uint32_t", [round(10 * 1.0 * (30000 / 1.0) ** (i / 127)) for i in range(128)], 8)
    L += arr("BFM_FIXED_SHOW", "uint32_t", [round(10 * 1.0 * (9000 / 1.0) ** (i / 127)) for i in range(128)], 8)
    hb = kaiser_halfband(23, 7.0)
    hbq = [round(v * 65536) for v in hb]        # Q16, rounded so the sum is 1.0 exactly
    hbq[len(hbq) // 2] += 65536 - sum(hbq)
    L += [f"#define BFM_HB_N {len(hbq)}"]
    L += arr("BFM_HB", "int32_t", hbq, 12)
    L += arr("BFM_TANH", "int16_t", [round(32767 * math.tanh((i - 128) / 32)) for i in range(257)], 16)
    # pitch of MIDI note 0 at the engine rate, Q32 cycles per sample (x 2^(oct) in bfm_inc)
    L += [f"#define BFM_INC0 {round((2 ** 32) * f0 / FS)}u", ""]
    open(sys.argv[1], "w").write("\n".join(L) + "\n")
    print(f"bfm tables: {len(RATIOS)} ratios, half-band {len(hbq)} taps -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
